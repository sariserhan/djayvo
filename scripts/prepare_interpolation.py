"""Emit the fixed full-band interpolation table; no audio or runtime dependency."""
import math
import struct


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


print('// Generated by scripts/prepare_interpolation.py; coefficients at cutoff 0.94.')
print('constexpr std::array<std::array<float, 16>, 65> full_band_interpolation = {{')
for phase in range(65):
    values = []
    for tap in range(16):
        distance = phase / 64.0 - (tap - 7)
        x = math.pi * distance * 0.94
        values.append(0.0 if abs(distance) >= 8 else
                      0.94 * (1.0 if abs(x) < 1e-12 else math.sin(x) / x) *
                      (0.5 + 0.5 * math.cos(math.pi * distance / 8)))
    total = sum(values)
    # Match the engine's float storage before double-precision normalization.
    row = [f32(f32(value) / total) for value in values]
    assert all(math.isfinite(value) for value in row) and abs(sum(row) - 1) < 1e-7
    print('    {{' + ', '.join(value.hex() + 'F' for value in row) + '}},')
print('}};')
