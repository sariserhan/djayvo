#!/usr/bin/env python3
"""Reproduce the pinned guitar bank using the existing acoustic PCM preparation."""
import hashlib
import json
from pathlib import Path
from prepare_acoustic_bank import ROOT, prepare


def main():
    manifest_path=ROOT/'assets/manifests/guitar-v1.json'
    manifest=json.loads(manifest_path.read_text())
    cache=ROOT/'renders/guitar-source';cache.mkdir(parents=True,exist_ok=True)
    text=['// Generated by scripts/prepare_guitar_bank.py; CC0-1.0.',
          '// Brian Wood / Karoryfer Lecolds. Pinned sources: assets/manifests/guitar-v1.json.']
    for entry in manifest['samples']:
        pcm,entry['prepared']=prepare(entry,cache)
        text.append(f"static constexpr std::int16_t {entry['id']}[] = {{")
        text.extend(','.join(str(v) for v in pcm[i:i+24])+',' for i in range(0,len(pcm),24))
        text.append('};')
    text.append('static constexpr InstrumentSample guitar_samples[] = {')
    for e in manifest['samples']:
        text.append(f"{{Instrument::guitar, {e['root_midi']}, {e['velocity_max']}, {e['take']}, {e['id']}, "
                    f"sizeof({e['id']})/sizeof({e['id']}[0]), 22050, {'true' if e['muted'] else 'false'}}},")
    text.append('};')
    output=ROOT/'core/instruments/guitar_bank.inc';output.write_text('\n'.join(text)+'\n')
    manifest['generated_file']=str(output.relative_to(ROOT))
    manifest['generated_sha256']=hashlib.sha256(output.read_bytes()).hexdigest()
    manifest_path.write_text(json.dumps(manifest,indent=2)+'\n')
    print('PASS: 78 prepared recorded guitar samples, 13 pitches, normal/staccato, layers and alternate takes')


if __name__=='__main__':main()
