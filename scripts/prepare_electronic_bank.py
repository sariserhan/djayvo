#!/usr/bin/env python3
"""Build original electronic one-shots from equations; no reference audio input."""
import array
import hashlib
import json
import math
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
RATE = 24000


def synth(instrument, pitch, take):
    seconds = 3.2 if instrument != 'drums' else {36: .7, 38: .5, 42: .16, 46: .6}[pitch]
    count = round(seconds*RATE)
    rng = random.Random(9107+pitch*13+take)
    frequency = 440*2**((pitch-69)/12)
    result=[];low=0;low2=0;noise_low=0
    for n in range(count):
        t=n/RATE
        if instrument=='bass':
            # Harmonics share one fundamental; a moving cutoff supplies the note's bite.
            cutoff=190+1700*math.exp(-t/0.11)
            raw=.6*math.sin(2*math.pi*frequency*t)
            raw+=sum(.35*math.sin(2*math.pi*frequency*k*t)/k for k in range(2,25) if frequency*k<RATE*.4)
            amplitude=.8+.2*math.exp(-t/.12)
        elif instrument=='piano':
            cutoff=1100+1100*math.exp(-t/.4)
            raw=sum(math.sin(2*math.pi*frequency*ratio*k*t+phase)/(k*k)
                    for ratio,phase in ((.998,0),(1.002,.7)) for k in range(1,10) if frequency*ratio*k<RATE*.4)/2
            amplitude=(1-math.exp(-t/.025))*(.55+.45*math.exp(-t/.7))
        else:
            noise=rng.uniform(-1,1)
            noise_low+=.22*(noise-noise_low)
            high=noise-noise_low
            cutoff=9000
            if pitch==36:
                phase=2*math.pi*(49*t+100*.025*(1-math.exp(-t/.025)))
                raw=math.sin(phase)*math.exp(-t/.16)+.11*high*math.exp(-t/.006)
            elif pitch==38:
                raw=.25*math.sin(2*math.pi*185*t)*math.exp(-t/.055)+.8*high*math.exp(-t/.09)
                # Three short noise bursts give the snare a handclap-like front.
                raw+=.2*high*sum(math.exp(-(t-start)/.007) for start in (0,.011,.022) if t>=start)
            else:
                raw=high*math.exp(-t/(.025 if pitch==42 else .13))
            amplitude=1
        alpha=1-math.exp(-2*math.pi*cutoff/RATE)
        low+=alpha*(raw-low);low2+=alpha*(low-low2)
        value=(low2 if instrument!='drums' else low)*amplitude
        fade=min(1,n/(RATE*.002),(count-1-n)/(RATE*.08))
        result.append(value*fade)
    peak=max(abs(x) for x in result)
    pcm=array.array('h',(round(x/peak*.88*32767) for x in result))
    assert pcm[0]==pcm[-1]==0 and max(abs(x) for x in pcm)<32767
    return pcm


def main():
    text=['// Original procedural electronic palette. Generated by scripts/prepare_electronic_bank.py.',
          '// No reference recordings or third-party sound sources. See assets/manifests/electronic-v1.json.']
    entries=[]
    for instrument,pitches,takes in [('piano',(48,60,72),(0,)),('bass',(36,43,48),(0,)),('drums',(36,38,42,46),(0,1))]:
        for pitch in pitches:
            for take in takes:
                name=f'electronic_{instrument}_{pitch}_{take}'
                pcm=synth(instrument,pitch,take)
                text.append(f'static constexpr std::int16_t {name}[] = {{')
                text.extend(','.join(str(v) for v in pcm[i:i+24])+',' for i in range(0,len(pcm),24))
                text.append('};')
                if sys.byteorder!='little':pcm.byteswap()
                entries.append({'id':name,'instrument':instrument,'root_midi':pitch,'velocity_max':127,'take':take,
                                'sample_rate':RATE,'frames':len(pcm),'pcm_sha256':hashlib.sha256(pcm.tobytes()).hexdigest()})
    text.append('static constexpr InstrumentSample electronic_samples[] = {')
    for e in entries:
        text.append(f"{{Instrument::{e['instrument']}, {e['root_midi']}, 127, {e['take']}, {e['id']}, {e['frames']}, {RATE}}},")
    text.append('};')
    data=('\n'.join(text)+'\n').encode()
    path=ROOT/'core/instruments/electronic_bank.inc';path.write_bytes(data)
    manifest={'name':'Djayvo original electronic palette v1','source':'Original equations and seeded noise in scripts/prepare_electronic_bank.py',
              'reference_audio_used':False,'third_party_sound_assets':False,'rights':'Original project material; follows the project outbound license',
              'generator_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'generated_file':str(path.relative_to(ROOT)),
              'generated_sha256':hashlib.sha256(data).hexdigest(),'samples':entries}
    (ROOT/'assets/manifests/electronic-v1.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'PASS: {len(entries)} original electronic one-shots; no reference audio consumed')


if __name__=='__main__':main()
