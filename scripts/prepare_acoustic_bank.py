#!/usr/bin/env python3
"""Reproduce the pinned CC0 instrument bank with Python's standard library only.

Original downloads stay in ignored renders/. Generated immutable PCM is compiled
into the engine: no file I/O, decoder, or allocation in audio processing.
"""
import argparse
import array
import hashlib
import json
import math
from pathlib import Path
import sys
import urllib.request
import wave

ROOT = Path(__file__).resolve().parents[1]


def prepare(entry, cache):
    path = cache / (entry['id'] + '.wav')
    if not path.exists():
        path.write_bytes(urllib.request.urlopen(entry['url'], timeout=60).read())
    if hashlib.sha256(path.read_bytes()).hexdigest() != entry['sha256']:
        raise ValueError('source hash mismatch: ' + entry['id'])
    with wave.open(str(path), 'rb') as source:
        channels, width, rate, frames, compression, _ = source.getparams()
        if channels not in (1, 2) or width not in (2, 3, 4) or compression != 'NONE':
            raise ValueError('unsupported instrument source')
        raw = source.readframes(frames)
    scale = 2 ** (width * 8 - 1)
    mono = [sum(int.from_bytes(raw[i+c*width:i+(c+1)*width], 'little', signed=True)
                for c in range(channels)) / (channels * scale)
            for i in range(0, len(raw), channels * width)]
    peak = max(abs(x) for x in mono)
    begin = next(i for i, x in enumerate(mono) if abs(x) > peak * 0.005)
    mono = mono[begin:begin + round(rate * entry['maximum_seconds'])]
    target = 22050
    cutoff = 0.94 * min(1, target / rate)
    radius = math.ceil(16 / cutoff)
    phases = {}
    result = []
    count = round(len(mono) * target / rate)
    for i in range(count):
        center, phase = divmod(i * rate, target)
        if phase not in phases:
            weights = []
            for j in range(-radius + 1, radius + 1):
                distance = phase / target - j
                if abs(distance) >= radius:
                    continue
                x = math.pi * distance * cutoff
                weight = cutoff * (math.sin(x) / x if abs(x) > 1e-12 else 1)
                weight *= 0.5 + 0.5 * math.cos(math.pi * distance / radius)
                weights.append((j, weight))
            phases[phase] = weights
        valid = [(center+j, w) for j, w in phases[phase] if 0 <= center+j < len(mono)]
        value = sum(mono[k]*w for k, w in valid) / sum(w for _, w in valid)
        result.append(value)
    gain = 0.85 / max(abs(x) for x in result)
    pcm = array.array('h', (round(x * gain * 32767 * min(1, i/(target*.001),
                           (count-1-i)/(target*.03))) for i, x in enumerate(result)))
    if sys.byteorder != 'little':
        pcm.byteswap()
    digest = hashlib.sha256(pcm.tobytes()).hexdigest()
    if sys.byteorder != 'little':
        pcm.byteswap()
    return pcm, {'frames': count, 'sample_rate': target, 'pcm_sha256': digest,
                 'source_trim_start_frame': begin, 'source_rate': rate,
                 'modifications': 'mono average; onset trim; duration cap; windowed-sinc resample; peak normalize to 0.85; 1 ms attack / 30 ms tail fades; PCM16'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=ROOT/'renders/acoustic-source')
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    manifest_path = ROOT/'assets/manifests/acoustic-v1.json'
    manifest = json.loads(manifest_path.read_text())
    text = ['// Generated by scripts/prepare_acoustic_bank.py. CC0-1.0.',
            '// Credits and pinned source hashes: assets/manifests/acoustic-v1.json.']
    for entry in manifest['samples']:
        pcm, metadata = prepare(entry, args.cache)
        entry['prepared'] = metadata
        text.append(f"static constexpr std::int16_t {entry['id']}[] = {{")
        text.extend(','.join(str(v) for v in pcm[i:i+24])+',' for i in range(0, len(pcm), 24))
        text.append('};')
        print(entry['id'], len(pcm), flush=True)
    text.append('static constexpr InstrumentSample samples[] = {')
    for e in manifest['samples']:
        text.append(f"{{Instrument::{e['instrument']}, {e['root_midi']}, {e['velocity_max']}, {e['take']}, {e['id']}, "
                    f"sizeof({e['id']})/sizeof({e['id']}[0]), 22050}},")
    text.append('};')
    output = ROOT/'core/instruments/acoustic_bank.inc'
    output.write_text('\n'.join(text)+'\n')
    manifest['generated_file'] = str(output.relative_to(ROOT))
    manifest['generated_sha256'] = hashlib.sha256(output.read_bytes()).hexdigest()
    manifest_path.write_text(json.dumps(manifest, indent=2)+'\n')


if __name__ == '__main__':
    main()
